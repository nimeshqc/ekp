const STAGE_BASE_MS: Record<IngestStage, number> = {
  parse: 420,
  clean: 130,
  chunk: 160,
  embed: 780,
  index: 210,
}

function syntheticDocText(filename: string): string {
  const base = filename.replace(/\.[^.]+$/, '').replace(/[-_]+/g, ' ')
  return [
    `${filename} — ingested document`,
    `This document, "${base}", was uploaded to the proposal workspace and processed entirely on-platform: parsed, cleaned, chunked, embedded on local CPU, and indexed into an isolated vector namespace. No content left the box and no external embedding API was called.`,
    `The document "${base}" covers the core subject matter provided for this proposal and is fully indexed for retrieval. Each chunk stores its page and character offsets, which is what makes exact source highlighting possible when a citation is clicked.`,
    `Ask any question whose answer lives in this document and the platform will return a grounded response citing the exact supporting passages. Questions the corpus cannot answer are refused rather than hallucinated.`,
  ].join('\n\n')
}

export interface UploadFileMeta {
  name: string
  sizeBytes: number
}

/** POST /api/ingest (SSE) */
export async function ingest(
  token: string,
  files: UploadFileMeta[],
  onEvent: (e: IngestEvent) => void,
): Promise<void> {
  const t0 = performance.now()
  const aggregate = { documents: 0, chunks: 0, tokens: 0, embeddings: 0, totalMs: 0 }

  for (const file of files) {
    const docId = `user-${uid()}`
    const ext = file.name.split('.').pop()?.toLowerCase() ?? 'txt'
    const isPdf = ext === 'pdf'

    // plausible numbers derived from size
    const words = Math.max(180, Math.min(24000, Math.round(file.sizeBytes / 6.2)))
    const chars = Math.round(words * 6.1)
    const pages = isPdf ? Math.max(1, Math.round(words / 420)) : null
    const chunks = Math.max(2, Math.round(chars / 680))
    const tokens = Math.round(words * 1.33)

    onEvent({ type: 'doc-start', docId, filename: file.name, sizeBytes: file.sizeBytes })

    const sizeFactor = 0.7 + Math.min(2.2, file.sizeBytes / 400_000)
    const stageRecords: DocStageRecord[] = []
    const metricsFor: Record<IngestStage, () => Record<string, string | number>> = {
      parse: () => ({ ...(pages ? { pages } : {}), words, chars }),
      clean: () => ({ chars, 'removed ws': Math.round(chars * 0.018) }),
      chunk: () => ({ chunks, 'avg chars': Math.round(chars / chunks), overlap: 120 }),
      embed: () => ({ embeddings: chunks, dim: VECTOR_DIM, batch: 32 }),
      index: () => ({ vectors: chunks, index: 'hnsw' }),
    }

    for (const stage of ['parse', 'clean', 'chunk', 'embed', 'index'] as IngestStage[]) {
      onEvent({ type: 'stage', docId, stage, status: 'started' })
      const ms = jitter(STAGE_BASE_MS[stage] * sizeFactor)
      await sleep(ms)
      const metrics = metricsFor[stage]()
      stageRecords.push({ stage, durationMs: ms, metrics })
      onEvent({ type: 'stage', docId, stage, status: 'completed', durationMs: ms, metrics })
    }

    const totalMs = stageRecords.reduce((s, r) => s + r.durationMs, 0)
    const stats: DocIngestStats = {
      docId,
      filename: file.name,
      sizeBytes: file.sizeBytes,
      pageCount: pages,
      wordCount: words,
      chunkCount: chunks,
      tokenCount: tokens,
      embeddingCount: chunks,
      vectorDim: VECTOR_DIM,
      embeddingModel: EMBEDDING_MODEL,
      totalMs,
      stages: stageRecords,
    }

    // persist mock parsed content so the source viewer (new tab) can render it
    const doc: SourceDoc = {
      docId,
      filename: file.name,
      kind: isPdf ? 'pdf' : ext === 'md' ? 'markdown' : 'text',
      pages: [{ page: 1, text: syntheticDocText(file.name) }],
    }
    save(`ekp.doc.${docId}`, doc)

    aggregate.documents += 1
    aggregate.chunks += chunks
    aggregate.tokens += tokens
    aggregate.embeddings += chunks

    bumpUsage(token, 'usedIngestions')
    const link = findLinkByToken(token)
    recordActivity({
      linkLabel: link?.label ?? token,
      kind: 'ingestion',
      detail: file.name,
      latencyMs: totalMs,
      tokens,
      estCostUsd: 0, // in-house embeddings: no API cost
      feedback: null,
    })

    onEvent({ type: 'doc-done', docId, stats })
  }

  aggregate.totalMs = Math.round(performance.now() - t0)
  onEvent({ type: 'done', aggregate })
}

// ---- query ----

function matchQA(question: string): CannedQA | null {
  const q = question.toLowerCase()
  let best: CannedQA | null = null
  let bestScore = 0
  for (const qa of DEFAULT_QA) {
    const score = qa.keywords.filter((k) => q.includes(k)).length
    if (score > bestScore) {
      bestScore = score
      best = qa
    }
  }
  return best
}

function getDoc(docId: string): SourceDoc | null {
  const preset = DEFAULT_DOCS.find((d) => d.docId === docId)
  if (preset) return preset
  return load<SourceDoc | null>(`ekp.doc.${docId}`, null)
}

function userCorpusAnswer(userDocIds: string[]): {
  answer: string
  citations: Citation[]
  followups: string[]
} {
  const docs = userDocIds.map(getDoc).filter((d): d is SourceDoc => d !== null).slice(0, 2)
  const citations = docs.map((doc, i) => {
    const base = doc.filename.replace(/\.[^.]+$/, '').replace(/[-_]+/g, ' ')
    const quote = `The document "${base}" covers the core subject matter provided for this proposal and is fully indexed for retrieval.`
    return citationFor(doc, quote, i + 1, 0.9 - i * 0.07)
  })
  const names = docs.map((d) => d.filename).join(' and ')
  const marks = citations.map((c) => `[${c.id}]`).join(' ')
  return {
    answer:
      `Based on your uploaded corpus (${names}), the relevant material has been parsed, chunked, and embedded on-platform, and this answer is grounded in the retrieved passages ${marks}. ` +
      `In the live platform this response is generated by ${LLM_MODEL} from the top-k retrieved chunks of your actual documents; in this mockup the retrieval pipeline, citations, offsets, and highlighting behave exactly as they will in production.`,
    citations,
    followups: [
      'Which passages were retrieved for this answer?',
      'How are my documents kept isolated from other clients?',
      'What does the ingestion pipeline do at each stage?',
    ],
  }
}

/** POST /api/query (SSE) */
export async function query(
  token: string,
  corpus: Corpus,
  question: string,
  userDocIds: string[],
  onEvent: (e: QueryEvent) => void,
): Promise<void> {
  const t0 = performance.now()

  onEvent({ type: 'stage', stage: 'embed-query', status: 'started' })
  await sleep(jitter(240))
  onEvent({ type: 'stage', stage: 'embed-query', status: 'completed', durationMs: jitter(38), info: `${VECTOR_DIM}-dim` })

  onEvent({ type: 'stage', stage: 'retrieve', status: 'started' })
  await sleep(jitter(320))

  let answer: string
  let citations: Citation[]
  let followups: string[]
  let grounded = true

  if (corpus === 'default') {
    const qa = matchQA(question)
    if (qa) {
      answer = qa.answer
      followups = qa.followups
      citations = qa.citations.map((c, i) => {
        const doc = getDoc(c.docId)
        if (!doc) throw new Error('mock: missing default doc')
        return citationFor(doc, c.quote, i + 1, c.score)
      })
    } else {
      grounded = false
      answer = UNGROUNDED_ANSWER
      citations = []
      followups = UNGROUNDED_FOLLOWUPS
    }
  } else {
    if (userDocIds.length === 0) {
      grounded = false
      answer = UNGROUNDED_ANSWER
      citations = []
      followups = UNGROUNDED_FOLLOWUPS
    } else {
      ;({ answer, citations, followups } = userCorpusAnswer(userDocIds))
    }
  }

  const retrievalMs = jitter(26, 0.8)
  onEvent({
    type: 'stage',
    stage: 'retrieve',
    status: 'completed',
    durationMs: retrievalMs,
    info: `top-${citations.length || 5}, threshold 0.30`,
  })
  onEvent({ type: 'sources', citations })
  onEvent({ type: 'grounded', grounded })

  onEvent({ type: 'stage', stage: 'generate', status: 'started' })
  const ttftDelay = jitter(520)
  await sleep(ttftDelay)
  const ttftMs = Math.round(performance.now() - t0)

  const words = answer.split(' ')
  for (let i = 0; i < words.length; i++) {
    onEvent({ type: 'token', text: (i === 0 ? '' : ' ') + words[i] })
    await sleep(14 + Math.random() * 26)
  }
  const genMs = Math.round(performance.now() - t0) - ttftDelay
  onEvent({ type: 'stage', stage: 'generate', status: 'completed', durationMs: genMs })

  await sleep(jitter(420))
  onEvent({ type: 'followups', questions: followups })

  const inputTokens = Math.round(question.split(' ').length * 1.4) + citations.length * 190 + 240
  const outputTokens = Math.round(words.length * 1.32)
  const totalMs = Math.round(performance.now() - t0)
  const stats = {
    retrievalMs,
    ttftMs,
    totalMs,
    inputTokens,
    outputTokens,
    model: LLM_MODEL,
    estCostUsd: inputTokens * COST_PER_INPUT_TOKEN + outputTokens * COST_PER_OUTPUT_TOKEN,
  }

  bumpUsage(token, 'usedQueries')
  const link = findLinkByToken(token)
  const queryId = `q_${uid()}`
  recordActivity({
    linkLabel: link?.label ?? token,
    kind: 'query',
    detail: question,
    latencyMs: totalMs,
    tokens: inputTokens + outputTokens,
    estCostUsd: stats.estCostUsd,
    feedback: null,
  })

  onEvent({ type: 'done', queryId, stats })
}

/** POST /api/feedback */
export async function sendFeedback(
  _queryId: string,
  verdict: Feedback,
  _reason?: string,
): Promise<void> {
  await sleep(jitter(180))
  // attach to most recent query activity row so the admin dashboard reflects it
  const events = getActivity()
  const target = events.find((e) => e.kind === 'query')
  if (target) {
    target.feedback = verdict
    save(ACTIVITY_KEY, events)
  }
}

