// ================================================================ admin API

const ADMIN_SESSION_KEY = 'ekp.admin'

/** POST /api/admin/login */
export async function adminLogin(username: string, password: string): Promise<void> {
  await sleep(jitter(500))
  if (!username || !password) throw new Error('invalid-credentials')
  sessionStorage.setItem(ADMIN_SESSION_KEY, '1')
}

export function adminLogout() {
  sessionStorage.removeItem(ADMIN_SESSION_KEY)
}

export function isAdminAuthed(): boolean {
  return sessionStorage.getItem(ADMIN_SESSION_KEY) === '1'
}

/** GET /api/admin/links */
export async function adminListLinks(): Promise<ProposalLink[]> {
  await sleep(jitter(300))
  return [...getLinks()].sort((a, b) => b.createdAt.localeCompare(a.createdAt))
}

/** POST /api/admin/links */
export async function adminCreateLink(req: CreateLinkRequest): Promise<ProposalLink> {
  await sleep(jitter(550))
  const link: ProposalLink = {
    id: `lnk_${uid()}`,
    label: req.label,
    url: `/p/tok-${uid()}`,
    createdAt: new Date().toISOString(),
    expiresAt: hoursFromNow(req.expiresInHours),
    maxIngestions: req.maxIngestions,
    usedIngestions: 0,
    maxQueries: req.maxQueries,
    usedQueries: 0,
    revoked: false,
  }
  putLinks([link, ...getLinks()])
  return link
}

/** POST /api/admin/links/:id/revoke */
export async function adminRevokeLink(id: string): Promise<void> {
  await sleep(jitter(350))
  const links = getLinks()
  const link = links.find((l) => l.id === id)
  if (link) {
    link.revoked = true
    putLinks(links)
  }
}

/** GET /api/admin/dashboard */
export async function adminDashboard(): Promise<DashboardData> {
  await sleep(jitter(400))
  const events = getActivity()
  const links = getLinks()
  const now = Date.now()
  const queries = events.filter((e) => e.kind === 'query')
  return {
    totals: {
      activeLinks: links.filter((l) => !l.revoked && Date.parse(l.expiresAt) > now).length,
      ingestions: events.filter((e) => e.kind === 'ingestion').length,
      queries: queries.length,
      tokens: events.reduce((s, e) => s + e.tokens, 0),
      estCostUsd: events.reduce((s, e) => s + e.estCostUsd, 0),
      likes: queries.filter((e) => e.feedback === 'like').length,
      dislikes: queries.filter((e) => e.feedback === 'dislike').length,
    },
    events,
  }
}
