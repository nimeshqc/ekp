/** Full text of a doc; page texts joined with a blank line. The viewer uses
 *  the same convention, so citation char offsets line up. */
export function docFullText(doc: SourceDoc): string {
  return doc.pages.map((p) => p.text).join('\n\n')
}

function pageOfOffset(doc: SourceDoc, charStart: number): number | null {
  if (doc.kind !== 'pdf') return null
  let cursor = 0
  for (const p of doc.pages) {
    const end = cursor + p.text.length
    if (charStart < end) return p.page
    cursor = end + 2 // '\n\n' separator
  }
  return doc.pages[doc.pages.length - 1]?.page ?? null
}

function citationFor(doc: SourceDoc, quote: string, id: number, score: number): Citation {
  const full = docFullText(doc)
  const start = full.indexOf(quote)
  if (start === -1) throw new Error(`mock: quote not found in ${doc.filename}`)
  return {
    id,
    docId: doc.docId,
    filename: doc.filename,
    page: pageOfOffset(doc, start),
    charStart: start,
    charEnd: start + quote.length,
    snippet: quote,
    score,
  }
}

