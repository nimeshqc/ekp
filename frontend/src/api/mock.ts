function putLinks(links: ProposalLink[]) {
  save(LINKS_KEY, links)
}

function tokenOf(link: ProposalLink): string {
  return link.url.split('/').pop() ?? ''
}

function findLinkByToken(token: string): ProposalLink | undefined {
  return getLinks().find((l) => tokenOf(l) === token)
}

function bumpUsage(token: string, field: 'usedIngestions' | 'usedQueries', by = 1) {
  const links = getLinks()
  const link = links.find((l) => tokenOf(l) === token)
  if (link) {
    link[field] += by
    putLinks(links)
  }
}

